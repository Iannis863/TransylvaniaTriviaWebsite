const initialTime = new Date("2026-11-01T10:00:00Z");
const input = (overrides: Partial<CustomEventInput> = {}) => customEventInputSchema.parse({ name: "Hermes", slug: "hermes", title: "Hermes Quiz", subtitle: "A special event", eventDate: "2026-12-25T08:00:00Z", isPublished: true, ...overrides });
const signup = (editionId: string, teamName: string) => ({ editionId, teamName, captainName: "Ana", email: "ana@example.com", memberCount: 4, language: "en" as const });
const partnerLogo = readFileSync(new URL("../tests/fixtures/custom-event-partner.png", import.meta.url));
const logoData = (bytes: Buffer) => `data:image/png;base64,${bytes.toString("base64")}`;
function paddedLogo(targetBytes: number): Buffer {
  const data = Buffer.alloc(targetBytes - partnerLogo.length - 12, 120);
  data.write("Comment\0", 0, "latin1");
  const chunk = Buffer.alloc(data.length + 12);
  chunk.writeUInt32BE(data.length); chunk.write("tEXt", 4); data.copy(chunk, 8);
  chunk.writeUInt32BE(pngCrc32(chunk.subarray(4, chunk.length - 4)), chunk.length - 4);
  return Buffer.concat([partnerLogo.subarray(0, partnerLogo.length - 12), chunk, partnerLogo.subarray(partnerLogo.length - 12)]);
}

